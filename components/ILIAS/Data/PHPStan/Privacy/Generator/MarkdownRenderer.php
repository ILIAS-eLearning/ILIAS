declare(strict_types=1);

namespace ILIAS\Data\Privacy\PHPStan\Generator;

/**
 * Renders the privacy data usage report of one component as Markdown.
 */
final class MarkdownRenderer
{
    public function render(string $component, ComponentReport $report): string
    {
        $now = new \DateTimeImmutable()->format('Y-m-d');
        $md = "# Privacy Data Usage – {$component}\n\n";
        $md .= "> Auto-generated by `scripts/Privacy/generate-privacy-docs.php` on {$now}.  \n";
        $md .= "> Do not edit manually – re-run the generator after code changes.\n\n";

        if ($report->isEmpty()) {
            return $md . "_This component does not resolve any privacy-protected data._\n";
        }

        $md .= "## Summary\n\n";
        $md .= $this->table(['Category', 'Count'], [
            ['Stored in DB', (string) count($report->get(EntryCategory::Store))],
            ['Displayed to user', (string) count($report->get(EntryCategory::Display))],
            ['Passed to component', (string) count($report->get(EntryCategory::Pass))],
            ['Technical processing', (string) count($report->get(EntryCategory::Technical))],
            ['Unmigrated (legacy access)', (string) count($report->get(EntryCategory::Legacy))],
        ]);

        if ($report->get(EntryCategory::Store) !== []) {
            $md .= "\n## Stored data\n\n_Data resolved for persistence in a database table._\n\n";
            $md .= $this->table(
                ['Type', 'Target table · column', 'File'],
                array_map(fn(ResolveEntry $e): array => [
                    "`{$e->privacy_type}`",
                    '`' . implode(' · ', $e->purpose_args) . '`',
                    $this->link($e),
                ], $report->get(EntryCategory::Store))
            );
        }

        if ($report->get(EntryCategory::Display) !== []) {
            $md .= "\n## Displayed to user\n\n_Data resolved for rendering in the UI._\n\n";
            $md .= $this->table(
                ['Type', 'UI context', 'File'],
                array_map(fn(ResolveEntry $e): array => [
                    "`{$e->privacy_type}`",
                    '`' . ($e->purpose_args[0] ?? '—') . '`',
                    $this->link($e),
                ], $report->get(EntryCategory::Display))
            );
        }

        if ($report->get(EntryCategory::Pass) !== []) {
            $md .= "\n## Passed to other components\n\n_Data resolved and forwarded to another component._\n\n";
            $md .= $this->table(
                ['Type', 'Target component', 'Reason', 'File'],
                array_map(fn(ResolveEntry $e): array => [
                    "`{$e->privacy_type}`",
                    '`' . ($e->purpose_args[0] ?? '—') . '`',
                    $e->purpose_args[1] ?? '—',
                    $this->link($e),
                ], $report->get(EntryCategory::Pass))
            );
        }

        if ($report->get(EntryCategory::Technical) !== []) {
            $md .= "\n## Technical processing\n\n_Data resolved for internal computation. Not persisted or displayed._\n\n";
            $md .= $this->table(
                ['Type', 'Operation', 'File'],
                array_map(fn(ResolveEntry $e): array => [
                    "`{$e->privacy_type}`",
                    '`' . ($e->purpose_args[0] ?? '—') . '`',
                    $this->link($e),
                ], $report->get(EntryCategory::Technical))
            );
        }

        if ($report->get(EntryCategory::Legacy) !== []) {
            $md .= "\n## Unmigrated (legacy access)\n\n";
            $md .= "_Resolves through deprecated code paths without a classified purpose."
                . " Each entry is a migration TODO._\n\n";
            $md .= $this->table(
                ['Type', 'Hint', 'File'],
                array_map(fn(ResolveEntry $e): array => [
                    "`{$e->privacy_type}`",
                    '`' . ($e->purpose_args[0] ?? '—') . '`',
                    $this->link($e),
                ], $report->get(EntryCategory::Legacy))
            );
        }

        $md .= "\n## GDPR relevance\n\n";
        $types = array_values(array_unique(array_map(
            static fn(ResolveEntry $e): string => "`{$e->privacy_type}`",
            $report->all()
        )));
        $targets = array_values(array_unique(array_filter(array_map(
            static fn(ResolveEntry $e): string => implode(' · ', $e->purpose_args),
            $report->get(EntryCategory::Store)
        ))));
        $recipients = array_values(array_unique(array_filter(array_map(
            static fn(ResolveEntry $e): string => $e->purpose_args[0] ?? '',
            $report->get(EntryCategory::Pass)
        ))));

        $rows = [['Personal data categories', implode(', ', $types)]];
        if ($targets !== []) {
            $rows[] = ['Storage locations', implode(', ', array_map(static fn($t): string => "`{$t}`", $targets))];
        }
        if ($recipients !== []) {
            $rows[] = ['Data recipients', implode(', ', array_map(static fn($r): string => "`{$r}`", $recipients))];
        }
        $rows[] = ['Legal basis', '_To be filled in manually_'];
        $rows[] = ['Retention period', '_To be filled in manually_'];

        return $md . $this->table(['GDPR aspect', 'Details'], $rows);
    }

    /**
     * @param list<string>       $headers
     * @param list<list<string>> $rows
     */
    private function table(array $headers, array $rows): string
    {
        if ($rows === []) {
            return "_None._\n";
        }

        $line = static fn(array $cells): string => '| ' . implode(' | ', $cells) . " |\n";
        $separator = '|' . str_repeat('---|', count($headers)) . "\n";

        return $line($headers) . $separator . implode('', array_map($line, $rows));
    }

    private function link(ResolveEntry $entry): string
    {
        $relative = preg_replace('#.*/components/ILIAS/#', '', str_replace('\\', '/', $entry->file));
        return "`{$relative}:{$entry->line}`";
    }
}
