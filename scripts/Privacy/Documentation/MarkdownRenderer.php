declare(strict_types=1);

namespace ILIAS\Scripts\Privacy\Documentation;

/**
 * Renders the generated privacy documentation of one component from the
 * use of privacy data types in its code.
 *
 * The output has the structure of a PRIVACY.md as described in
 * docs/development/how-to-write-a-privacy.md. Every resolve() call becomes
 * a sentence in its section, built from the phrases of its technical
 * requirement (where, to whom, what for, under which condition); calls with
 * the same phrases are merged into one sentence. Code facts that are no
 * documentation (code locations, tables, technical processing, deprecated
 * accessors) follow as notes for the authors in an HTML comment.
 *
 * The file is generated next to the handwritten PRIVACY.md and grows with
 * every privacy data type until it can replace it. It contains no date and
 * no line numbers, so it only changes when what the code does with
 * personal data changes.
 */
class MarkdownRenderer
{
    private const string NOT_DOCUMENTED = '…';

    /**
     * @var array<string, EntryCategory|null> section => category it is generated from
     */
    private const array SECTIONS = [
        'Integrated components' => EntryCategory::Pass,
        'Data being stored' => EntryCategory::Store,
        'Data being presented' => EntryCategory::Display,
        'Data being deleted' => null,
        'Data being exported' => EntryCategory::Export,
    ];

    /**
     * @param \Closure(string): bool $has_privacy_md whether a component has a handwritten PRIVACY.md
     */
    public function render(string $component, ComponentReport $report, \Closure $has_privacy_md): string
    {
        $md = "<!--\n"
            . "Generated by scripts/Privacy/generate-privacy-docs.php from the use of privacy data types in the\n"
            . "code of the component. Do not edit manually.\n"
            . "It is created alongside the handwritten PRIVACY.md and is meant to replace it once it covers\n"
            . "everything; until then, the handwritten PRIVACY.md stays authoritative.\n"
            . "-->\n\n";
        $md .= "# {$component} Privacy\n\n";
        $md .= "> **Disclaimer: This documentation does not guarantee completeness or accuracy. Please report any\n"
            . "> missing or incorrect information via the [ILIAS issue tracker](https://mantis.ilias.de) or a\n"
            . "> [Pull Request](../../../docs/development/contributing.md#pull-request-to-the-repositories).**\n";

        foreach (self::SECTIONS as $title => $category) {
            $sentences = $category !== null ? $this->sentences($category, $report, $has_privacy_md) : [];
            $md .= "\n## {$title}\n\n";
            if ($sentences === []) {
                $md .= '_This section has not been documented here yet. This does not mean that no personal data is'
                    . ' processed' . ($has_privacy_md($component)
                    ? '; see the handwritten [PRIVACY.md](PRIVACY.md)._'
                    : '._') . "\n";
                continue;
            }
            foreach ($sentences as $sentence) {
                $md .= "- {$sentence}\n";
            }
        }

        return $md . $this->notesForAuthors($component, $report, $has_privacy_md);
    }

    /**
     * One sentence per distinct set of phrases; the data of all calls with
     * the same phrases is named together.
     *
     * @param \Closure(string): bool $has_privacy_md
     * @return list<string>
     */
    private function sentences(EntryCategory $category, ComponentReport $report, \Closure $has_privacy_md): array
    {
        $labels = [];
        foreach ($report->get($category) as $entry) {
            $phrases = $this->phrases($entry);
            $key = json_encode($phrases, JSON_THROW_ON_ERROR);
            $labels[$key][$this->label($entry)] = true;
        }
        ksort($labels);

        $sentences = [];
        foreach ($labels as $key => $data) {
            $data = array_keys($data);
            sort($data);
            $phrases = json_decode($key, true, 512, JSON_THROW_ON_ERROR);
            $sentences[] = $this->sentence($category, $phrases, $data, $has_privacy_md);
        }
        sort($sentences);
        return $sentences;
    }

    /**
     * @param array<string, string> $p
     * @param list<string>          $data
     * @param \Closure(string): bool $has_privacy_md
     */
    private function sentence(EntryCategory $category, array $p, array $data, \Closure $has_privacy_md): string
    {
        $subject = $this->enumerate($data);
        $be = count($data) > 1 ? 'are' : 'is';
        $if = ($p['condition'] ?? '') !== '' ? "If {$p['condition']}, " : '';

        $sentence = match ($category) {
            EntryCategory::Store => "{$subject} {$be} stored to {$p['in_order_to']}.",
            EntryCategory::Display => "{$subject} {$be} presented {$p['where']} to {$p['to']}, to {$p['in_order_to']}.",
            EntryCategory::Export => "{$p['by']} can export {$subject} {$p['where']}, to {$p['in_order_to']}.",
            EntryCategory::Pass => $this->linked($p['component'], $has_privacy_md)
                . ": receives {$subject} to {$p['in_order_to']}",
            default => '',
        };

        return $category === EntryCategory::Pass ? $sentence : $if . ($if === '' ? ucfirst($sentence) : $sentence);
    }

    /**
     * The phrases of the technical requirement of an entry; phrases not
     * known from the code are marked.
     *
     * @return array<string, string>
     */
    private function phrases(ResolveEntry $entry): array
    {
        $names = match ($entry->category) {
            EntryCategory::Store => ['in_order_to', 'condition'],
            EntryCategory::Display => ['where', 'to', 'in_order_to', 'condition'],
            EntryCategory::Export => ['where', 'by', 'in_order_to', 'condition'],
            EntryCategory::Pass => ['component', 'in_order_to'],
            default => [],
        };
        $phrases = [];
        foreach ($names as $name) {
            $value = $entry->requirement_args[$name] ?? '';
            $phrases[$name] = $this->isKnown($value) ? $value : ($name === 'condition' && $value === '' ? '' : self::NOT_DOCUMENTED);
        }
        return $phrases;
    }

    private function isKnown(string $value): bool
    {
        return $value !== '' && !str_starts_with($value, '{');
    }

    private function hasUnknownPhrase(ResolveEntry $entry): bool
    {
        return in_array(self::NOT_DOCUMENTED, $this->phrases($entry), true);
    }

    /**
     * @param list<string> $items
     */
    private function enumerate(array $items): string
    {
        $last = array_pop($items);
        return $items === [] ? (string) $last : implode(', ', $items) . ' and ' . $last;
    }

    /**
     * @param \Closure(string): bool $has_privacy_md
     */
    private function linked(string $component, \Closure $has_privacy_md): string
    {
        return $has_privacy_md($component) ? "[{$component}](../{$component}/PRIVACY.md)" : $component;
    }

    private function label(ResolveEntry $entry): string
    {
        $type = $entry->privacy_type;
        return class_exists($type) && is_subclass_of($type, \ILIAS\Data\Privacy\PrivacyDataType::class)
            ? $type::label()
            : $this->shortType($entry);
    }

    /**
     * @param \Closure(string): bool $has_privacy_md
     */
    private function notesForAuthors(string $component, ComponentReport $report, \Closure $has_privacy_md): string
    {
        $md = "\n<!--\nNotes for authors: not part of the privacy documentation. Only personal data handled through\n"
            . "privacy data types is visible here; data the code handles otherwise, e.g. user IDs, is not.\n";
        if (!$has_privacy_md($component)) {
            $md .= "\n- The component has no handwritten PRIVACY.md yet.\n";
        }

        $rows = [];
        foreach (self::SECTIONS as $title => $category) {
            if ($category === null) {
                continue;
            }
            foreach ($this->sorted($report->get($category)) as $entry) {
                $rows[] = [
                    $title,
                    "`{$this->shortType($entry)}`",
                    $category === EntryCategory::Store ? '`' . ($entry->requirement_args['target'] ?? '?') . '`' : '',
                    $this->link($entry),
                ];
            }
        }
        if ($rows !== []) {
            $md .= "\n### Uses in the code\n\n" . $this->table(['Section', 'Data', 'Table', 'Code'], $rows);
        }

        $incomplete = [];
        foreach (self::SECTIONS as $category) {
            if ($category === null) {
                continue;
            }
            foreach ($report->get($category) as $entry) {
                if ($this->hasUnknownPhrase($entry)) {
                    $incomplete[] = $entry;
                }
            }
        }

        $notes = [
            ['Phrases not known from the code', $incomplete,
                'A phrase of the technical requirement is not a literal string or constant; it is shown as "'
                . self::NOT_DOCUMENTED . '" above.'],
            ['Technical processing', $report->get(EntryCategory::Technical),
                'Resolved for a computation only, neither stored nor presented.'],
            ['Unclassified', $report->get(EntryCategory::Unclassified),
                'The technical requirement could not be determined from the code. State it where the value is'
                . ' resolved.'],
            ['Not yet migrated', $report->get(EntryCategory::Legacy),
                'A deprecated accessor releases the value without a technical requirement. Callers of the'
                . ' accessor, also in other components, are not listed; while it exists, the documentation is'
                . ' incomplete for this data.'],
        ];
        foreach ($notes as [$title, $entries, $description]) {
            if ($entries === []) {
                continue;
            }
            $md .= "\n### {$title}\n\n_{$description}_\n\n" . $this->table(
                ['Data', 'Requirement', 'Code'],
                array_map(fn(ResolveEntry $e): array => [
                    "`{$this->shortType($e)}`",
                    '`' . implode(' · ', [$e->requirement_class, ...array_values($e->requirement_args)]) . '`',
                    $this->link($e),
                ], $this->sorted($entries))
            );
        }

        // "-->" would end the comment early
        return str_replace('-->', '‐‐>', $md) . "-->\n";
    }

    /**
     * @param list<ResolveEntry> $entries
     * @return list<ResolveEntry>
     */
    private function sorted(array $entries): array
    {
        usort(
            $entries,
            fn(ResolveEntry $a, ResolveEntry $b): int => [$this->link($a), $a->privacy_type, $a->requirement_args]
                <=> [$this->link($b), $b->privacy_type, $b->requirement_args]
        );
        return $entries;
    }

    /**
     * @param list<string>       $headers
     * @param list<list<string>> $rows
     */
    private function table(array $headers, array $rows): string
    {
        $line = static fn(array $cells): string => '| ' . implode(' | ', array_map(
            static fn(string $cell): string => str_replace('|', '\|', $cell),
            $cells
        )) . " |\n";
        $separator = '|' . str_repeat('---|', count($headers)) . "\n";

        return $line($headers) . $separator . implode('', array_unique(array_map($line, $rows)));
    }

    /**
     * File and function, without the line: a line number would change with
     * every unrelated edit of the file.
     */
    private function link(ResolveEntry $entry): string
    {
        $location = $entry->location !== '' ? " `{$entry->location}`" : '';
        return "`{$this->path($entry)}`{$location}";
    }

    private function shortType(ResolveEntry $entry): string
    {
        return basename(str_replace('\\', '/', $entry->privacy_type));
    }

    private function path(ResolveEntry $entry): string
    {
        return preg_replace('#.*/components/ILIAS/#', '', str_replace('\\', '/', $entry->file)) ?? $entry->file;
    }
}
